#!/usr/bin/env python3
"""Verify or safely fetch the pinned Analogue Pocket diagnostic reference."""

from __future__ import annotations

import argparse
import hashlib
import os
from pathlib import Path
import shutil
import sys
import tarfile
import tempfile
from urllib.error import URLError
from urllib.request import urlopen


REVISION = "da3a021b1eaf742604d86d8dc9b33a6666263e6a"
ARCHIVE_URL = (
    "https://codeload.github.com/open-fpga/core-template/tar.gz/" + REVISION
)
ARCHIVE_SHA256 = "c2553fdf893d9836fd15b0189cb7e70c29e569dea9e064e6612dd256124f0421"
# Digest of the sorted path/type/file-content manifest from that archive.
TREE_SHA256 = "1b5482168710415709adaf53f82bd2028b43f73638bc53f72ab2965e9083ef45"
ROOT_NAME = f"core-template-{REVISION}"
MAX_ARCHIVE_BYTES = 25 * 1024 * 1024

# Source: docs/POCKET_DIAGNOSTIC_INPUTS.md. These pins are required even when
# the full source archive is regenerated by GitHub.
FILE_HASHES = {
    "src/fpga/core/core_top.v": "a036e934d56cb44c980f49c33583fe71449f6fa6a2f2bd41145590cdcb2f3666",
    "src/fpga/core/mf_pllbase/mf_pllbase_0002.v": "07c1a739bebf75cbababa24fb4097d7a18850e29f4aa2ae38c343f1fdf126c39",
    "src/fpga/ap_core.qpf": "a911d8909682cd12e9d963a88f106b816f5f737f7008d7ac8f6304de138825c9",
    "src/fpga/ap_core.qsf": "65d1b8989e6efa2e4d9cd361d03493a26dbda601a8fa9058b151c4fb7360acaf",
    "src/fpga/core/core_constraints.sdc": "c0ffbe130cfcdd588a2ab32fe1a891ce2fa12ef1723a39d4ed1062b57acf90d7",
    "video.json": "1ce4b3d954ecd78cebd103bcafca7225a7c2e21f9a586d9cbd30579bb8b4a49c",
}


class FetchError(Exception):
    """An actionable fetch or verification failure."""


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def validate_files(root: Path) -> None:
    if not root.is_dir() or root.is_symlink():
        raise FetchError(f"reference directory is missing or is a symlink: {root}")
    problems = []
    for relative, expected in FILE_HASHES.items():
        candidate = root / relative
        if not candidate.is_file() or candidate.is_symlink():
            problems.append(f"missing required regular file: {relative}")
            continue
        actual = sha256_file(candidate)
        if actual != expected:
            problems.append(
                f"hash mismatch for {relative}: expected {expected}, got {actual}"
            )
    if problems:
        raise FetchError("reference verification failed:\n  " + "\n  ".join(problems))
    manifest = hashlib.sha256()
    for path in sorted(root.rglob("*")):
        relative = path.relative_to(root).as_posix().encode("utf-8")
        if path.is_symlink():
            raise FetchError(f"reference contains an unsafe symbolic link: {path}")
        if path.is_dir():
            manifest.update(b"D\0" + relative + b"\0")
        elif path.is_file():
            manifest.update(b"F\0" + relative + b"\0")
            manifest.update(hashlib.sha256(path.read_bytes()).digest())
        else:
            raise FetchError(f"reference contains a special file: {path}")
    actual_tree = manifest.hexdigest()
    if actual_tree != TREE_SHA256:
        raise FetchError(
            f"reference tree manifest mismatch: expected {TREE_SHA256}, got {actual_tree}"
        )


def checked_destination(reference_root: Path, destination: Path) -> Path:
    root = reference_root.resolve()
    target = destination.resolve()
    if target == root or root not in target.parents:
        raise FetchError(f"destination must be inside {root}: {destination}")
    return target


def safe_member_path(name: str) -> tuple[str, ...]:
    # Tar uses POSIX separators. Reject backslashes too, since they can be
    # separators on Windows and make the same archive unsafe across platforms.
    if not name or "\\" in name or name.startswith("/"):
        raise FetchError(f"unsafe archive path: {name!r}")
    raw_parts = name[:-1].split("/") if name.endswith("/") else name.split("/")
    parts = tuple(raw_parts)
    if not parts or any(part in ("", ".", "..") for part in parts):
        raise FetchError(f"unsafe archive path: {name!r}")
    if ":" in parts[0]:
        raise FetchError(f"unsafe drive-qualified archive path: {name!r}")
    if parts[0] != ROOT_NAME:
        raise FetchError(f"unexpected archive root in path: {name!r}")
    return parts


def extract_checked(archive: Path, stage: Path) -> Path:
    expected_root = stage / ROOT_NAME
    seen: set[tuple[str, ...]] = set()
    total_size = 0
    try:
        with tarfile.open(archive, mode="r:gz") as tar:
            for member in tar:
                parts = safe_member_path(member.name)
                if parts in seen:
                    raise FetchError(f"duplicate archive path: {member.name!r}")
                seen.add(parts)
                target = stage.joinpath(*parts)
                if member.isdir():
                    target.mkdir(parents=True, exist_ok=True)
                    continue
                if not member.isreg():
                    raise FetchError(
                        f"unsupported archive entry (links and special files are rejected): {member.name!r}"
                    )
                if member.size < 0:
                    raise FetchError(f"negative archive entry size: {member.name!r}")
                total_size += member.size
                if total_size > MAX_ARCHIVE_BYTES:
                    raise FetchError("archive expands beyond the 25 MiB safety limit")
                target.parent.mkdir(parents=True, exist_ok=True)
                source = tar.extractfile(member)
                if source is None:
                    raise FetchError(f"cannot read archive entry: {member.name!r}")
                with source, target.open("xb") as output:
                    shutil.copyfileobj(source, output)
    except (tarfile.TarError, OSError) as exc:
        if isinstance(exc, FetchError):
            raise
        raise FetchError(f"cannot read archive {archive}: {exc}") from exc
    if not expected_root.is_dir():
        raise FetchError(f"archive does not contain expected root {ROOT_NAME}/")
    validate_files(expected_root)
    return expected_root


def verify_archive_hash(archive: Path) -> None:
    actual = sha256_file(archive)
    if actual != ARCHIVE_SHA256:
        raise FetchError(
            f"archive SHA-256 mismatch: expected {ARCHIVE_SHA256}, got {actual}"
        )


def download_archive(destination: Path) -> None:
    try:
        with urlopen(ARCHIVE_URL, timeout=30) as response, destination.open("wb") as out:
            total = 0
            while True:
                block = response.read(1024 * 1024)
                if not block:
                    break
                total += len(block)
                if total > MAX_ARCHIVE_BYTES:
                    raise FetchError("download exceeds the 25 MiB safety limit")
                out.write(block)
    except (URLError, OSError) as exc:
        raise FetchError(f"could not download pinned reference from {ARCHIVE_URL}: {exc}") from exc


def import_archive(archive: Path, reference_root: Path, destination: Path) -> None:
    if not archive.is_file():
        raise FetchError(f"archive does not exist or is not a file: {archive}")
    verify_archive_hash(archive)
    reference_root.mkdir(parents=True, exist_ok=True)
    destination = checked_destination(reference_root, destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".diagnostic-reference-", dir=destination.parent) as tmp:
        stage = Path(tmp)
        extracted = extract_checked(archive, stage)
        if destination.exists():
            validate_files(destination)
            print(f"Already present and verified; left untouched: {destination}")
            return
        try:
            os.rename(extracted, destination)
        except FileExistsError:
            # Another process won the race. Never replace it.
            validate_files(destination)
            print(f"Already present and verified; left untouched: {destination}")
            return
    print(f"Imported pinned reference {REVISION}: {destination}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--archive", type=Path, help="import this local pinned .tar.gz")
    mode.add_argument("--download", action="store_true", help="download the pinned official archive")
    parser.add_argument(
        "--destination",
        type=Path,
        help="cache directory inside Pocket/build/reference (defaults to the pinned cache)",
    )
    args = parser.parse_args()

    repo = Path(__file__).resolve().parents[2]
    reference_root = repo / "Pocket/build/reference"
    default_destination = reference_root / ROOT_NAME
    destination = args.destination or default_destination
    try:
        destination = checked_destination(reference_root, destination)
        if args.archive:
            import_archive(args.archive.resolve(), reference_root, destination)
        elif args.download:
            reference_root.mkdir(parents=True, exist_ok=True)
            with tempfile.TemporaryDirectory(prefix=".diagnostic-download-", dir=reference_root) as tmp:
                archive = Path(tmp) / "reference.tar.gz"
                download_archive(archive)
                import_archive(archive, reference_root, destination)
        else:
            validate_files(destination)
            print(f"Verified pinned reference {REVISION}: {destination}")
        return 0
    except FetchError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
